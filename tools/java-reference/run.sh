#!/usr/bin/env bash
# Builds the Java Freerouting engine and dumps reference outputs for every fixture.
#
#   tools/java-reference/run.sh JAVA_REPO MODE [MAX_PASSES] [TIMEOUT] [NAME_FILTER]
#
# JAVA_REPO  checkout of danbrunski/freerouting (the port is pinned to cda540f)
# MODE       load  -> fixtures/reference/load/*.json  (parse + board statistics)
#            route -> fixtures/reference/route/*.json and *.ses (batch autorouter)
#
# Needs: python3 + pip (for a Java 25 runtime from the jdk4py wheel), curl, and the
# Gradle wrapper in JAVA_REPO (only used to resolve dependencies). No JDK 25 install is
# required: sources are compiled with the Eclipse compiler (ECJ) on the jdk4py runtime.
# Set JAVA=/path/to/java (Java 25+) to use an existing runtime instead.
set -euo pipefail

JAVA_REPO=$(cd "$1" && pwd)
MODE=$2
shift 2
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
WORK=${REFERENCE_WORK_DIR:-$ROOT/target/java-reference}
ECJ_VERSION=3.46.100
mkdir -p "$WORK"
export LANG=C.UTF-8 LC_ALL=C.UTF-8

if [[ -z "${JAVA:-}" ]]; then
  if [[ ! -x "$WORK/jdk4py/jdk4py/java-runtime/bin/java" ]]; then
    python3 -m pip download -q --no-deps jdk4py==25.0.2.1 -d "$WORK/wheel"
    python3 -c "import zipfile,glob,sys; zipfile.ZipFile(glob.glob(sys.argv[1]+'/*.whl')[0]).extractall(sys.argv[2])" \
      "$WORK/wheel" "$WORK/jdk4py"
    chmod +x "$WORK"/jdk4py/jdk4py/java-runtime/bin/*
  fi
  JAVA="$WORK/jdk4py/jdk4py/java-runtime/bin/java"
fi

ECJ="$WORK/ecj-$ECJ_VERSION.jar"
[[ -f "$ECJ" ]] || curl -sSfL -o "$ECJ" \
  "https://repo1.maven.org/maven2/org/eclipse/jdt/ecj/$ECJ_VERSION/ecj-$ECJ_VERSION.jar"

CP_FILE="$JAVA_REPO/build/reference-classpath.txt"
if [[ ! -f "$CP_FILE" ]]; then
  # Maven Central sometimes answers 429; Gradle keeps what it already fetched, so retry.
  for attempt in 1 2 3 4 5 6; do
    (cd "$JAVA_REPO" && ./gradlew --no-daemon --no-configuration-cache -q \
      -I "$HERE/classpath.init.gradle" referenceClasspath) && break
    echo "dependency resolution failed (attempt $attempt), retrying" >&2
    sleep 45
  done
fi
DEPS=$(cat "$CP_FILE")

CLASSES="$WORK/classes"
if [[ ! -d "$CLASSES/app" ]]; then
  # Constants.java is normally generated by the Gradle build.
  mkdir -p "$WORK/gen/app/freerouting/constants"
  cat > "$WORK/gen/app/freerouting/constants/Constants.java" <<JAVA
package app.freerouting.constants;

public final class Constants {
  public static final String FREEROUTING_VERSION = "$(git -C "$JAVA_REPO" rev-parse --short HEAD)";
  public static final String FREEROUTING_BUILD_DATE = "reference";
}
JAVA
  find "$JAVA_REPO/src/main/java" "$WORK/gen" -name '*.java' > "$WORK/sources.txt"
  JAVA_TOOL_OPTIONS= "$JAVA" -Xmx4g -jar "$ECJ" --release 25 -nowarn -encoding UTF-8 \
    -cp "$DEPS" -d "$CLASSES" @"$WORK/sources.txt"
fi

CP="$CLASSES:$JAVA_REPO/src/main/resources:$DEPS"
JAVA_TOOL_OPTIONS= "$JAVA" -jar "$ECJ" --release 25 -nowarn -encoding UTF-8 -cp "$CP" \
  -d "$WORK/harness" "$HERE/src/reference/ReferenceDump.java"

JAVA_TOOL_OPTIONS= "$JAVA" -Xmx6g -Djava.awt.headless=true -Dsun.jnu.encoding=UTF-8 \
  -Dfile.encoding=UTF-8 -Dreference.casesDir="$HERE/cases" -cp "$WORK/harness:$CP" \
  reference.ReferenceDump "$MODE" "${REFERENCE_FIXTURES_DIR:-$ROOT/fixtures}" \
  "${REFERENCE_OUT_DIR:-$ROOT/fixtures/reference}" "$@"
